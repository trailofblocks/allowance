#!/usr/bin/env node
// Writes src/abi.ts from `forge build` output, so the SDK carries typed ABIs without needing Foundry.
// tests/abi.test.ts fails if the committed file drifts from the contracts.
//
//   forge build && node scripts/gen-abi.mjs

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const CONTRACTS = [
  ["allowanceModuleAbi", "AllowanceModule.sol", "AllowanceModule"],
  ["agentAccountAbi", "AgentAccount.sol", "AgentAccount"],
  ["eip3009TokenAbi", "MockEIP3009Token.sol", "MockEIP3009Token"],
];

export function renderAbiFile() {
  let out = "// Generated by scripts/gen-abi.mjs from `forge build` output. Do not edit by hand.\n";
  for (const [name, file, contract] of CONTRACTS) {
    const artifact = JSON.parse(readFileSync(path.join(root, "out", file, `${contract}.json`), "utf8"));
    out += `\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, "src", "abi.ts"), renderAbiFile());
  console.log("wrote src/abi.ts");
}
